-- =============================================================================
-- SICGA - Sistema administrativo Centro Gallego
-- Esquema PostgreSQL (>= 13) generado a partir de SICGA.12.5.11.accdb
--
-- Dos esquemas:
--   legacy  -> copia 1:1 sin transformar de las 26 tablas de Access. La crea y
--              llena el ETL (02_etl_access_to_pg.py). Sirve de respaldo y de
--              auditoria: nada se pierde aunque una fila no pase a "public".
--   public  -> modelo normalizado definido en este archivo. Es el que usara Django.
--
-- Convenciones:
--   * snake_case, singular para tablas.
--   * PK sustituta "id" (IDENTITY BY DEFAULT, compatible con BigAutoField de Django).
--   * Los codigos de negocio de Access (P001, M001, ...) quedan como UNIQUE.
--   * Importes con el dominio "dinero" (NUMERIC(18,4)): hay importes de hasta
--     10.082.761.350 (bolivares previos a las reconversiones) y valores con mas
--     de 2 decimales, por eso no se usa NUMERIC(12,2).
--   * Toda FK lleva su indice (PostgreSQL no lo crea automaticamente).
--
-- Script idempotente: se puede ejecutar varias veces.
-- =============================================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS legacy;

DROP TABLE IF EXISTS
    public.migracion_incidencia,
    public.uso_salon,
    public.activo_fijo,
    public.proveedor,
    public.libro_diario,
    public.cheque_emitido,
    public.deposito,
    public.cheque_recibido,
    public.abono,
    public.factura,
    public.concesion_mensualidad,
    public.concesion,
    public.beneficiario,
    public.socio_mensualidad,
    public.socio_cuota_extra,
    public.socio,
    public.cuota_extra,
    public.tarifa_mensual,
    public.calendario_cobro,
    public.configuracion,
    public.banco,
    public.tipo_pago,
    public.provincia,
    public.usuario_sistema,
    public.nivel_acceso
CASCADE;

DROP DOMAIN IF EXISTS public.dinero CASCADE;
DROP DOMAIN IF EXISTS public.mes CASCADE;
DROP DOMAIN IF EXISTS public.anio CASCADE;

CREATE DOMAIN public.dinero AS NUMERIC(18,4);
CREATE DOMAIN public.mes    AS SMALLINT CHECK (VALUE BETWEEN 1 AND 12);
CREATE DOMAIN public.anio   AS SMALLINT CHECK (VALUE BETWEEN 1900 AND 2100);

-- -----------------------------------------------------------------------------
-- Seguridad / catalogos
-- -----------------------------------------------------------------------------

-- Access: NIVEL
CREATE TABLE public.nivel_acceso (
    id          SMALLINT     PRIMARY KEY,           -- 0 = acceso total, 1 = consulta
    descripcion VARCHAR(100) NOT NULL
);

-- Access: USUARIOS. La columna "Clave" (texto plano) NO se migra:
-- la autenticacion pasara a Django (hash PBKDF2) y cada usuario fija su clave.
CREATE TABLE public.usuario_sistema (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(30)  NOT NULL,
    nombre          VARCHAR(150),
    cedula          VARCHAR(15),
    nivel_acceso_id SMALLINT     NOT NULL REFERENCES public.nivel_acceso (id),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX ux_usuario_sistema_username ON public.usuario_sistema (lower(username));
CREATE INDEX ix_usuario_sistema_nivel ON public.usuario_sistema (nivel_acceso_id);

-- Access: PROVINCIAS (provincias gallegas de origen)
CREATE TABLE public.provincia (
    id     SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

-- Access: TIPOSPAGOS (M001 mantenimiento, Z002 cuota extraordinaria, A00x alquileres/concesiones...)
CREATE TABLE public.tipo_pago (
    id          SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(4)   NOT NULL UNIQUE,
    descripcion VARCHAR(100) NOT NULL
);

-- Access: BANCOS (cuentas propias del club). FLAG 1 = cuenta bancaria, 2 = efectivo / cargo en cuenta
CREATE TABLE public.banco (
    id                 SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(30) NOT NULL UNIQUE,
    numero_cuenta      VARCHAR(30),
    saldo              dinero      NOT NULL DEFAULT 0,
    es_cuenta_bancaria BOOLEAN     NOT NULL DEFAULT TRUE
);

-- -----------------------------------------------------------------------------
-- Parametrizacion (Access: MONTOS, MONTOSAA)
-- -----------------------------------------------------------------------------

-- Fila unica con los parametros globales que en Access vivian en MONTOS.
-- Los contadores (ultima_factura, ...) se mantienen por compatibilidad; en el
-- backend nuevo conviene sustituirlos por SEQUENCEs.
CREATE TABLE public.configuracion (
    id                    SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    periodo_actual        anio     NOT NULL,           -- MONTOS.Periodo
    mensualidad           dinero,                      -- MONTOS.Mensual
    mensualidad_uso       dinero,                      -- MONTOS.MensualUso
    ultima_factura        INTEGER,                     -- MONTOS.UltFac
    ultimo_numero_control INTEGER,                     -- MONTOS.UltCont
    ultimo_voucher        INTEGER,                     -- MONTOS.UltV
    total_acciones_propietario INTEGER,                -- MONTOS.TAcP
    total_acciones_uso    INTEGER,                     -- MONTOS.TAcU
    divisas_inicio        INTEGER,                     -- MONTOS.DivInicio
    fecha_inicio_divisas  DATE                         -- MONTOS.FechaIniDiv
);

-- Dia de corte de cada mes (MONTOS.Ene..Dic = '31/01', '28/02', ...)
CREATE TABLE public.calendario_cobro (
    mes        mes      PRIMARY KEY,
    dia_corte  SMALLINT NOT NULL CHECK (dia_corte BETWEEN 1 AND 31)
);

-- Cuota mensual por anio y mes.
-- Origen: MONTOSAA (anios anteriores) + MONTOS.MensEne..MensDic (periodo actual).
CREATE TABLE public.tarifa_mensual (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio  anio    NOT NULL,
    mes   mes     NOT NULL,
    monto dinero  NOT NULL,
    CONSTRAINT uq_tarifa_mensual UNIQUE (anio, mes)
);

-- Cuotas extraordinarias del periodo (MONTOS.CuotaExtra1..12 / Desc1..12 / Fecha1..12)
CREATE TABLE public.cuota_extra (
    id                SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero            SMALLINT    NOT NULL UNIQUE CHECK (numero BETWEEN 1 AND 12),
    descripcion       VARCHAR(80),
    monto             dinero      NOT NULL DEFAULT 0,
    fecha_vencimiento DATE
);

-- -----------------------------------------------------------------------------
-- Socios y beneficiarios
-- -----------------------------------------------------------------------------

-- Access: SOCIOS. Las columnas repetidas por mes (ENE..DIC, FENE..FDIC) y por
-- cuota (Cuota1..12, FC1..12) se normalizan en socio_mensualidad y socio_cuota_extra.
CREATE TABLE public.socio (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(4)   NOT NULL UNIQUE,     -- IDSocio: P001 (propietario) / U001 (uso)
    tipo_socio            CHAR(1)      NOT NULL CHECK (tipo_socio IN ('P', 'U')),
    accion_adicional      BOOLEAN      NOT NULL DEFAULT FALSE,   -- AcAdic
    apellidos             VARCHAR(150),
    nombres               VARCHAR(150),
    cedula                VARCHAR(15),                      -- normalizada sin puntos ni comas
    grupo_sanguineo       VARCHAR(10),                      -- RH
    fecha_nacimiento      DATE,
    lugar_nacimiento      VARCHAR(255),
    nacionalidad          VARCHAR(30),
    provincia_id          SMALLINT     REFERENCES public.provincia (id),
    es_gallego            BOOLEAN      NOT NULL DEFAULT FALSE,
    ascendencia_gallega   BOOLEAN      NOT NULL DEFAULT FALSE,
    estado_civil          CHAR(1)      CHECK (estado_civil IN ('S', 'C', 'D', 'V', 'U')),
    profesion             VARCHAR(30),
    direccion_habitacion  VARCHAR(255),
    telefono_habitacion   VARCHAR(15),
    celular               VARCHAR(15),
    email                 VARCHAR(60),
    email_alterno         VARCHAR(60),
    empresa               VARCHAR(80),
    direccion_trabajo     VARCHAR(255),
    web_trabajo           VARCHAR(30),
    telefono_trabajo      VARCHAR(15),
    fax                   VARCHAR(15),
    marca_vehiculo        VARCHAR(20),
    placa_vehiculo        VARCHAR(10),
    aficiones             VARCHAR(255),
    tiempo_en_ciudad      VARCHAR(20),
    domicilio_cobro       VARCHAR(255),
    fecha_ingreso         DATE,
    referencia_1          VARCHAR(10),                      -- Ref1 (codigo de socio que lo presenta)
    referencia_2          VARCHAR(10),                      -- Ref2
    exonerado             BOOLEAN      NOT NULL DEFAULT FALSE,   -- Ex = 'EXONERADA'
    exonerado_total       BOOLEAN      NOT NULL DEFAULT FALSE,   -- ExT
    observaciones         TEXT,                             -- Obs1 + Obs2 + Obs3
    ruta_foto             VARCHAR(255),                     -- RutaSocio (las fotos OLE estan vacias)
    act_legado            BOOLEAN      NOT NULL DEFAULT FALSE,   -- Act  (semantica por confirmar)
    band_legado           BOOLEAN      NOT NULL DEFAULT FALSE    -- Band: "Accion que paga cuota de mantenimiento"
                                                                    -- (IngSocios); morosos/solventes exigen Band
);
CREATE INDEX ix_socio_cedula     ON public.socio (cedula);
CREATE INDEX ix_socio_apellidos  ON public.socio (apellidos, nombres);
CREATE INDEX ix_socio_provincia  ON public.socio (provincia_id);

-- Estado de pago de la mensualidad por socio / anio / mes.
-- origen: SOCIOS (periodo actual, fuente viva), RELSOLV (historico de solvencia),
--         MOROSOS (anios que solo aparecen en el reporte de morosos).
CREATE TABLE public.socio_mensualidad (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id       BIGINT      NOT NULL REFERENCES public.socio (id) ON DELETE CASCADE,
    anio           anio        NOT NULL,
    mes            mes         NOT NULL,
    pagado         BOOLEAN     NOT NULL DEFAULT FALSE,
    numero_factura VARCHAR(10),
    monto_tarifa   dinero,                                   -- MOROSOS.MensXxx cuando existe
    origen         VARCHAR(10) NOT NULL CHECK (origen IN ('SOCIOS', 'RELSOLV', 'MOROSOS')),
    CONSTRAINT uq_socio_mensualidad UNIQUE (socio_id, anio, mes)
);
CREATE INDEX ix_socio_mensualidad_pendiente ON public.socio_mensualidad (anio, mes) WHERE NOT pagado;

-- Pago de cada cuota extraordinaria por socio (SOCIOS.Cuota1..12 / FC1..12)
CREATE TABLE public.socio_cuota_extra (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id       BIGINT      NOT NULL REFERENCES public.socio (id) ON DELETE CASCADE,
    cuota_extra_id SMALLINT    NOT NULL REFERENCES public.cuota_extra (id),
    pagada         BOOLEAN     NOT NULL DEFAULT FALSE,
    numero_factura VARCHAR(10),
    CONSTRAINT uq_socio_cuota_extra UNIQUE (socio_id, cuota_extra_id)
);
CREATE INDEX ix_socio_cuota_extra_cuota ON public.socio_cuota_extra (cuota_extra_id);

-- Access: BENEFICIARIOS (familiares del socio)
CREATE TABLE public.beneficiario (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(7)   NOT NULL UNIQUE,         -- IdBen: P001-1
    socio_id          BIGINT       NOT NULL REFERENCES public.socio (id) ON DELETE CASCADE,
    nombre_completo   VARCHAR(255),
    cedula            VARCHAR(15),
    parentesco        VARCHAR(20),
    fecha_nacimiento  DATE,
    grupo_sanguineo   VARCHAR(10),
    telefono          VARCHAR(15),
    email             VARCHAR(60),
    marca_vehiculo    TEXT,
    placa_vehiculo    VARCHAR(10),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    ruta_foto         VARCHAR(255)
);
CREATE INDEX ix_beneficiario_socio  ON public.beneficiario (socio_id);
CREATE INDEX ix_beneficiario_cedula ON public.beneficiario (cedula);

-- -----------------------------------------------------------------------------
-- Concesiones (restaurant, fuente de soda, escuelas...)
-- Access: CONCESION + RELSOLVCONC + MORCONC
-- -----------------------------------------------------------------------------
CREATE TABLE public.concesion (
    id                 SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_pago_id       SMALLINT     NOT NULL UNIQUE REFERENCES public.tipo_pago (id),  -- CONC = codigo de TIPOSPAGOS
    nombre             VARCHAR(255) NOT NULL,
    rif                VARCHAR(20),
    porcentaje_aporte  NUMERIC(7,4) NOT NULL DEFAULT 0         -- PORAP (0.04 = 4 %)
);

CREATE TABLE public.concesion_mensualidad (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concesion_id   SMALLINT    NOT NULL REFERENCES public.concesion (id) ON DELETE CASCADE,
    anio           anio        NOT NULL,
    mes            mes         NOT NULL,
    pagado         BOOLEAN     NOT NULL DEFAULT FALSE,
    numero_factura VARCHAR(10),
    origen         VARCHAR(12) NOT NULL CHECK (origen IN ('CONCESION', 'RELSOLVCONC', 'MORCONC')),
    CONSTRAINT uq_concesion_mensualidad UNIQUE (concesion_id, anio, mes)
);

-- -----------------------------------------------------------------------------
-- Facturacion y cobros
-- -----------------------------------------------------------------------------

-- Access: FACTURAS.
-- * numero NO es unico en el origen (73 numeros repetidos en facturas distintas).
-- * socio_id es opcional: hay facturas a terceros (alquiler de salon, concesiones,
--   otros) con IdSocio vacio. Si el codigo existia pero no se encontro el socio,
--   se conserva en codigo_socio_legado.
CREATE TABLE public.factura (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                 VARCHAR(10),
    numero_control         VARCHAR(12),                  -- N°Cont
    socio_id               BIGINT       REFERENCES public.socio (id) ON DELETE RESTRICT,
    codigo_socio_legado    VARCHAR(10),
    cliente_nombre         VARCHAR(150),                 -- NomyApel
    cliente_rif            VARCHAR(20),                  -- CIoRIF
    tipo_pago_id           SMALLINT     REFERENCES public.tipo_pago (id),
    descripcion            VARCHAR(150),
    fecha_emision          DATE,                         -- FecGenFact
    fecha_tope             DATE,                         -- FecTOPFact
    fecha_cancelacion      DATE,                         -- FecCanc
    monto                  dinero       NOT NULL DEFAULT 0,
    monto_cheque           dinero       NOT NULL DEFAULT 0,
    monto_deposito         dinero       NOT NULL DEFAULT 0,
    monto_tarjeta_debito   dinero       NOT NULL DEFAULT 0,
    monto_tarjeta_credito  dinero       NOT NULL DEFAULT 0,
    monto_efectivo         dinero       NOT NULL DEFAULT 0,
    numero_cuotas          SMALLINT,                     -- NumCuo
    estado                 BOOLEAN      NOT NULL DEFAULT TRUE,   -- Estado
    es_aporte              BOOLEAN      NOT NULL DEFAULT FALSE,  -- Ap
    anulada                BOOLEAN      NOT NULL DEFAULT FALSE,  -- Nula
    fecha_anulacion        DATE,
    pago_divisas           BOOLEAN      NOT NULL DEFAULT FALSE,
    monto_divisas          dinero
);
CREATE INDEX ix_factura_numero        ON public.factura (numero);
CREATE INDEX ix_factura_socio         ON public.factura (socio_id);
CREATE INDEX ix_factura_tipo_pago     ON public.factura (tipo_pago_id);
CREATE INDEX ix_factura_fecha_emision ON public.factura (fecha_emision);

-- Access: ABONOS (pagos parciales y notas de credito "NCmmaa" con monto negativo)
CREATE TABLE public.abono (
    id                       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_documento         VARCHAR(10)  NOT NULL,      -- N°Fact
    socio_id                 BIGINT       NOT NULL REFERENCES public.socio (id) ON DELETE RESTRICT,
    cliente_nombre           VARCHAR(150),
    cliente_rif              VARCHAR(20),
    tipo_pago_id             SMALLINT     REFERENCES public.tipo_pago (id),
    descripcion              VARCHAR(150),
    fecha_emision            DATE,
    fecha_cancelacion        DATE,
    monto                    dinero       NOT NULL DEFAULT 0,
    monto_cheque             dinero       NOT NULL DEFAULT 0,
    monto_deposito           dinero       NOT NULL DEFAULT 0,
    monto_tarjeta_debito     dinero       NOT NULL DEFAULT 0,
    monto_tarjeta_credito    dinero       NOT NULL DEFAULT 0,
    monto_efectivo           dinero       NOT NULL DEFAULT 0,
    estado                   BOOLEAN      NOT NULL DEFAULT TRUE,
    anulado                  BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_anulacion          DATE,
    numero_factura_relacionada VARCHAR(10),              -- FactC
    factura_relacionada_id   BIGINT       REFERENCES public.factura (id) ON DELETE SET NULL,
    anio_deuda               anio
);
CREATE INDEX ix_abono_socio   ON public.abono (socio_id);
CREATE INDEX ix_abono_numero  ON public.abono (numero_documento);
CREATE INDEX ix_abono_factura ON public.abono (factura_relacionada_id);

-- Access: CHEQUES (cheques recibidos de socios)
CREATE TABLE public.cheque_recibido (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id            BIGINT       REFERENCES public.socio (id) ON DELETE RESTRICT,
    codigo_socio_legado VARCHAR(10),
    numero_cheque       VARCHAR(15),
    numero_cuenta       VARCHAR(20),
    banco_emisor        VARCHAR(255),                    -- banco del socio, texto libre
    fecha_pago          DATE,
    descripcion         VARCHAR(150),
    monto               dinero       NOT NULL DEFAULT 0,
    numero_factura      VARCHAR(10),
    factura_id          BIGINT       REFERENCES public.factura (id) ON DELETE SET NULL
);
CREATE INDEX ix_cheque_recibido_socio   ON public.cheque_recibido (socio_id);
CREATE INDEX ix_cheque_recibido_factura ON public.cheque_recibido (factura_id);

-- Access: DEPOSITOS (depositos / transferencias de socios a cuentas del club)
CREATE TABLE public.deposito (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id            BIGINT       REFERENCES public.socio (id) ON DELETE RESTRICT,
    codigo_socio_legado VARCHAR(10),
    numero_deposito     VARCHAR(20),
    banco_id            SMALLINT     REFERENCES public.banco (id),
    banco_nombre        VARCHAR(255),                    -- texto original
    fecha_pago          DATE,
    descripcion         VARCHAR(150),
    monto               dinero       NOT NULL DEFAULT 0,
    numero_factura      VARCHAR(10),
    factura_id          BIGINT       REFERENCES public.factura (id) ON DELETE SET NULL
);
CREATE INDEX ix_deposito_socio   ON public.deposito (socio_id);
CREATE INDEX ix_deposito_banco   ON public.deposito (banco_id);
CREATE INDEX ix_deposito_factura ON public.deposito (factura_id);
CREATE INDEX ix_deposito_fecha   ON public.deposito (fecha_pago);

-- Access: "CHEQUES CG" (egresos: cheques / pagos emitidos por el club).
-- Las columnas solo de impresion (MONTOTEXTO, MONTO EN LETRAS, FECHA (DIA Y MES), AÑO)
-- se regeneran desde fecha/monto; el original queda en legacy.cheques_cg.
CREATE TABLE public.cheque_emitido (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           DATE,
    numero_cheque   VARCHAR(15)  UNIQUE,                 -- NULL permitido (pagos sin cheque)
    numero_cuenta   VARCHAR(20),
    banco_id        SMALLINT     REFERENCES public.banco (id),
    banco_nombre    VARCHAR(30),
    beneficiario    VARCHAR(50),
    monto           dinero       NOT NULL DEFAULT 0,
    concepto        VARCHAR(250),
    -- Monto en letras tal como se imprimio (en Access lo escribia el cajero): reimpresion identica
    monto_en_letras   VARCHAR(95),
    monto_en_letras_2 VARCHAR(30),
    numero_voucher  VARCHAR(10),
    lugar           VARCHAR(20),
    preparado_por   VARCHAR(10),
    anulado         BOOLEAN      NOT NULL DEFAULT FALSE,
    pago_divisas    BOOLEAN      NOT NULL DEFAULT FALSE,
    monto_divisas   dinero
);
CREATE INDEX ix_cheque_emitido_fecha ON public.cheque_emitido (fecha);
CREATE INDEX ix_cheque_emitido_banco ON public.cheque_emitido (banco_id);

-- Access: LIBDIA (libro diario de caja)
CREATE TABLE public.libro_diario (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura         VARCHAR(10),
    factura_id             BIGINT       REFERENCES public.factura (id) ON DELETE SET NULL,
    socio_id               BIGINT       REFERENCES public.socio (id) ON DELETE RESTRICT,
    codigo_socio_legado    VARCHAR(10),
    cliente_nombre         VARCHAR(150),
    cliente_rif            VARCHAR(20),
    tipo_pago_id           SMALLINT     REFERENCES public.tipo_pago (id),
    descripcion            VARCHAR(150),
    fecha_emision          DATE,
    fecha_tope             DATE,
    fecha_cancelacion      DATE,
    monto                  dinero       NOT NULL DEFAULT 0,
    monto_cheque           dinero       NOT NULL DEFAULT 0,
    monto_deposito         dinero       NOT NULL DEFAULT 0,
    monto_tarjeta_debito   dinero       NOT NULL DEFAULT 0,
    monto_tarjeta_credito  dinero       NOT NULL DEFAULT 0,
    monto_efectivo         dinero       NOT NULL DEFAULT 0,
    numero_cuotas          SMALLINT,
    estado                 BOOLEAN      NOT NULL DEFAULT TRUE,
    anulada                BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_anulacion        DATE,
    numero_voucher         VARCHAR(10),
    pago_cheque            dinero,
    pago_efectivo          dinero,
    pago_cargo_cuenta      dinero,
    banco_nombre           VARCHAR(25)
);
CREATE INDEX ix_libro_diario_factura ON public.libro_diario (factura_id);
CREATE INDEX ix_libro_diario_socio   ON public.libro_diario (socio_id);

-- -----------------------------------------------------------------------------
-- Otros
-- -----------------------------------------------------------------------------

-- Access: PROVEEDOR
CREATE TABLE public.proveedor (
    id             SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(5)   UNIQUE,
    nombre_empresa VARCHAR(100) NOT NULL,
    suministro     VARCHAR(255),
    direccion      VARCHAR(150),
    telefono       VARCHAR(15),
    representante  VARCHAR(100),
    celular        VARCHAR(15)
);

-- Access: ACTIVOS (inventario de activos fijos)
CREATE TABLE public.activo_fijo (
    id            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(5)   UNIQUE,
    descripcion   VARCHAR(255) NOT NULL,
    cantidad      INTEGER      NOT NULL DEFAULT 1 CHECK (cantidad >= 0),
    ubicacion     VARCHAR(150),
    fecha_ingreso DATE,
    fecha_salida  DATE,
    CHECK (fecha_salida IS NULL OR fecha_ingreso IS NULL OR fecha_salida >= fecha_ingreso)
);

-- Access: USOSALON
CREATE TABLE public.uso_salon (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id    BIGINT       NOT NULL REFERENCES public.socio (id) ON DELETE CASCADE,
    fecha_uso   DATE         NOT NULL,
    observacion VARCHAR(150)
);
CREATE INDEX ix_uso_salon_socio ON public.uso_salon (socio_id);

-- -----------------------------------------------------------------------------
-- Bitacora de la migracion: filas rechazadas, valores corregidos y referencias
-- no resueltas. La llena el ETL; sirve para depurar datos antes de salir a produccion.
-- -----------------------------------------------------------------------------
CREATE TABLE public.migracion_incidencia (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_origen  VARCHAR(40)  NOT NULL,
    clave_origen  VARCHAR(60),
    tipo          VARCHAR(20)  NOT NULL CHECK (tipo IN ('RECHAZADA', 'CORREGIDA', 'REF_NO_RESUELTA', 'DUPLICADA')),
    detalle       TEXT         NOT NULL,
    datos         JSONB,
    creado_en     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Seguimiento: una persona revisa la incidencia pendiente y deja constancia
    resuelta         BOOLEAN      NOT NULL DEFAULT FALSE,
    nota_resolucion  TEXT,
    resuelta_por     VARCHAR(150),
    resuelta_en      TIMESTAMPTZ
);
CREATE INDEX ix_migracion_incidencia_tabla ON public.migracion_incidencia (tabla_origen, tipo);

COMMIT;
